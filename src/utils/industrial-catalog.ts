/**
 * Synchronous fast description resolver (Curated + Decoder rules)
 */
export function getQuickDescription(partNumber: string): string {
  const cleanCode = partNumber.trim().toUpperCase();
  if (!cleanCode) return '';
  if (CURATED_PARTS[cleanCode]) return CURATED_PARTS[cleanCode];
  const ruleDesc = decodeByIndustrialRules(cleanCode);
  if (ruleDesc) return ruleDesc;
  return `MÓDULO DE AUTOMATIZACIÓN ${cleanCode}`;
}
